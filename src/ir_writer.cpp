std::string IRWriter::quote(std::string_view name) {
    bool simple = !name.empty();
    for (size_t i = 0; i < name.size(); ++i) {
        char c = name[i];
        bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
                  (c >= '0' && c <= '9') || c == '_' || c == '.' || c == '$';
        if (!ok || (i == 0 && c >= '0' && c <= '9')) {
            simple = false;
            break;
        }
    }
    if (simple) return std::string(name);
    std::string out = "\"";
    for (char c : name) {
        if (c == '"' || c == '\\') out += '\\';
        out += c;
    }
    out += '"';
    return out;
}

std::string IRWriter::string_const(std::string_view content) {
    std::string sym = ".str." + std::to_string(next_str_++);
    size_t len = content.size() + 1;  // 含 null 结尾

    std::string esc;
    for (unsigned char c : content) {
        if (c >= 32 && c < 127 && c != '"' && c != '\\') {
            esc += static_cast<char>(c);
        } else {
            char buf[8];
            std::snprintf(buf, sizeof(buf), "\\%02X", c);
            esc += buf;
        }
    }
    esc += "\\00";

    globals_ << "@" << sym << " = private unnamed_addr constant ["
             << len << " x i8] c\"" << esc << "\", align 1\n";
    return sym;
}

void IRWriter::emit_header() {
    header_ << "; module generated by clux\n";
    header_ << "target triple = \"x86_64-redhat-linux-gnu\"\n";
}

void IRWriter::flush() {
    out_ << header_.str();
    if (uses_pthread_) out_ << "declare i32 @pthread_create(ptr, ptr, ptr, ptr)\n";
    if (uses_malloc_)   out_ << "declare ptr @malloc(i64)\n";
    out_ << "\n";
    out_ << globals_.str();
    if (!globals_.str().empty()) out_ << "\n";
    out_ << body_.str();
    out_ << late_.str();
    out_ << tail_.str();
}

